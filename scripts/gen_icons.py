#!/usr/bin/env python3
"""Regenerate Sources/DevTasks/IconData.swift from a Font Awesome all.css file.
Usage: python3 scripts/gen_icons.py path/to/all.css
"""
import re, sys
css = open(sys.argv[1]).read()
pairs = re.findall(r'((?:\.fa-[a-z0-9-]+::?before,?\s*)+)\{\s*content:\s*"\\([0-9a-f]+)"', css)
seen, lines = set(), []
for sels, code in pairs:
    for name in re.findall(r'\.fa-([a-z0-9-]+)::?before', sels):
        if name not in seen:
            seen.add(name); lines.append(f"{name}:{code}")
out = "// Generated by scripts/gen_icons.py. Do not edit.\nlet faIconData = \"\"\"\n" + "\n".join(lines) + "\n\"\"\"\n"
open("Sources/DevTasks/IconData.swift", "w").write(out)
print(len(lines), "icons")
